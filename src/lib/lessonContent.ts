export function findCurated(lesson: string): LessonContent | null {
  const normalized = lesson.replace(/[\s（）()《》·、，,。:：-]/g, "").toLowerCase();
  const direct = Object.keys(CURATED).find(
    (key) => key.replace(/[\s（）()《》·、，,。:：-]/g, "").toLowerCase() === normalized,
  );
  if (direct) return CURATED[direct];
  const hints: { test: RegExp; key: string }[] = [
    { test: /分数/, key: "分数的初步认识" },
    { test: /秋天|秋雨/, key: "秋天的雨" },
    { test: /小数/, key: "小数的意义" },
    { test: /种子|发芽/, key: "种子发芽实验" },
    { test: /权利|宪法/, key: "公民的基本权利" },
    { test: /乘法/, key: "表内乘法（一）" },
    { test: /闰土/, key: "少年闰土" },
    { test: /school|学校/i, key: "My School" },
  ];
  for (const hint of hints) {
    if (hint.test.test(lesson)) return CURATED[hint.key];
  }
  return null;
}